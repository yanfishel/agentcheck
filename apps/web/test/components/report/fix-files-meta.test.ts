import { FIX_FILES_MAX_ATTEMPTS } from "@agentcheck/db";
import { describe, expect, it } from "vitest";
import {
	categoryPitch,
	FIX_ATTEMPTS_MAX,
	groupTodos,
	highlight,
	kindsForCategory,
} from "@/components/report/fix-files/file-meta";

const tones = (kind: Parameters<typeof highlight>[0], text: string) =>
	highlight(kind, text)
		.filter((s) => s.tone)
		.map((s) => [s.tone, s.text]);

describe("fix file meta", () => {
	it("matches the database's attempt limit", () => {
		expect(FIX_ATTEMPTS_MAX).toBe(FIX_FILES_MAX_ATTEMPTS);
	});

	it("maps categories to kinds", () => {
		expect(kindsForCategory("ai-manifests")).toEqual([
			"llms",
			"llms-full",
			"markdown",
		]);
		expect(kindsForCategory("bot-access")).toEqual(["robots"]);
		expect(kindsForCategory("content-semantics")).toEqual(["head"]);
		expect(kindsForCategory("agentic-actionability")).toEqual([]);
	});

	it("words the footer pitch for the applicable kinds", () => {
		expect(categoryPitch(["llms", "llms-full", "markdown"])).toBe(
			"Get ready llms.txt and llms-full.txt built from your site's pages, and a markdown version of this page.",
		);
		expect(categoryPitch(["llms", "markdown"])).toBe(
			"Get ready llms.txt built from your site's pages, and a markdown version of this page.",
		);
		expect(categoryPitch(["markdown"])).toBe(
			"Get a ready markdown version of this page.",
		);
		expect(categoryPitch(["llms", "llms-full"])).toBe(
			"Get ready llms.txt and llms-full.txt built from your site's pages.",
		);
		expect(categoryPitch(["llms"])).toBe(
			"Get a ready llms.txt built from your site's pages.",
		);
	});

	it("colours llms-full and markdown like llms.txt", () => {
		for (const kind of ["llms-full", "markdown"] as const) {
			expect(tones(kind, "# Site\n[About](https://e.com/a)")).toEqual([
				["key", "# Site"],
				["string", "[About]"],
				["flag", "https://e.com/a"],
			]);
		}
	});

	it("highlights a long line of unclosed brackets or comments in linear time", () => {
		const bs = String.fromCharCode(92);
		const lines = [
			"[".repeat(50_000),
			`${bs}[`.repeat(25_000),
			"<!--".repeat(12_500),
		];
		for (const kind of ["llms", "llms-full", "markdown", "head"] as const) {
			for (const line of lines) {
				const text = `# Page\n\n${line}\n`;
				const start = performance.now();
				const segments = highlight(kind, text);
				expect(performance.now() - start).toBeLessThan(500);
				expect(segments.map((s) => s.text).join("")).toBe(text);
			}
		}
	});

	it("still colours bracketed text and comments within the bounds", () => {
		expect(tones("markdown", `[${"a".repeat(300)}]`)).toEqual([
			["string", `[${"a".repeat(300)}]`],
		]);
		expect(tones("llms", "<!-- TODO: x -->")).toEqual([
			["warn", "<!-- TODO: x -->"],
		]);
	});

	it("keeps the text intact", () => {
		const samples = {
			robots:
				"# Generated by AgentCheck\nUser-agent: GPTBot\nAllow: /\nSitemap: https://example.com/sitemap.xml\n",
			llms: "# Example\n\n> A site.\n\n## Pages\n\n- [About \\(us\\)](https://example.com/about): <!-- TODO: add a description of /about -->\n",
			head: '<!-- Add inside <head> -->\n<meta property="og:title" content="Example">\n<meta property="og:image" content="TODO: an image URL">\n<script type="application/ld+json">\n{\n  "@type": "WebSite",\n  "url": "https://example.com/",\n  "name": "A \\"quoted\\" name"\n}\n</script>\n',
		} as const;
		for (const [kind, text] of Object.entries(samples)) {
			const segments = highlight(kind as keyof typeof samples, text);
			expect(segments.map((s) => s.text).join("")).toBe(text);
		}
	});

	it("colours robots.txt", () => {
		expect(
			tones("robots", "# note\nUser-agent: *\nSitemap: https://e.com/s.xml"),
		).toEqual([
			["muted", "# note"],
			["key", "User-agent"],
			["key", "Sitemap"],
			["flag", "https://e.com/s.xml"],
		]);
	});

	it("colours llms.txt", () => {
		expect(
			tones(
				"llms",
				"# Site\n- [About](https://e.com/a): <!-- TODO: add a description of /a -->\n<!-- x -->",
			),
		).toEqual([
			["key", "# Site"],
			["string", "[About]"],
			["flag", "https://e.com/a"],
			["warn", "<!-- TODO: add a description of /a -->"],
			["muted", "<!-- x -->"],
		]);
	});

	it("colours head.html", () => {
		expect(
			tones(
				"head",
				'<!-- c -->\n<meta content="TODO: x">\n"url": "https://e.com/", "name": "N"',
			),
		).toEqual([
			["muted", "<!-- c -->"],
			["key", "<meta"],
			["warn", '"TODO: x"'],
			["key", ">"],
			["key", '"url"'],
			["flag", '"https://e.com/"'],
			["key", '"name"'],
			["string", '"N"'],
		]);
	});

	it("groups TODOs by file and folds page descriptions", () => {
		const groups = groupTodos([
			{
				name: "llms.txt",
				todos: [
					{ text: "llms.txt: add a description of /politics/" },
					{ text: "llms.txt: add a description of /law/" },
					{ text: "llms.txt: add a description of the site" },
				],
			},
			{
				name: "head.html",
				todos: [
					{
						text: "head.html: og:image, a 1200×630 picture (none found on the page)",
					},
				],
			},
		]);
		expect(groups).toEqual([
			{
				file: "llms.txt",
				items: ["Add a description of the site"],
				pages: ["/politics/", "/law/"],
			},
			{
				file: "head.html",
				items: ["og:image, a 1200×630 picture (none found on the page)"],
				pages: [],
			},
		]);
	});

	it("keeps a single page description as a plain item", () => {
		expect(
			groupTodos([
				{
					name: "llms.txt",
					todos: [{ text: "llms.txt: add a description of /about" }],
				},
			]),
		).toEqual([
			{
				file: "llms.txt",
				items: ["Add a description of /about"],
				pages: [],
			},
		]);
	});
});
