import robotsParserModule from "robots-parser";
import { AI_BOTS } from "../checks/ai-bots-allowed.ts";

// robots-parser ships CJS typings that TypeScript resolves as the module namespace under NodeNext.
type RobotsParser = typeof import("robots-parser").default;
const robotsParser = robotsParserModule as unknown as RobotsParser;

export interface RobotsRewrite {
	content: string;
	/** What was changed, one entry per change (also written to the "# Changed:" line). */
	changed: string[];
	/** AI crawlers from `AI_BOTS` that the original file blocked on the audited URL. */
	blockedBots: string[];
}

interface ParsedLine {
	index: number;
	raw: string;
	/** Lowercased field name, or null for blank, comment and malformed lines. */
	field: string | null;
	value: string;
}

interface Block {
	/** The `User-agent:` lines with their normalised tokens. */
	agents: { line: ParsedLine; token: string }[];
	/** The lines after the `User-agent:` lines, up to the next block. */
	members: ParsedLine[];
}

const RULE_FIELDS = new Set(["allow", "disallow", "crawl-delay"]);
const FIELD_NAMES: Record<string, string> = {
	allow: "Allow",
	disallow: "Disallow",
	"crawl-delay": "Crawl-delay",
};

/** Mirrors robots-parser: lowercase, version suffix (`bot/1.0`) dropped. */
function agentToken(userAgent: string): string {
	const lower = userAgent.toLowerCase();
	const slash = lower.indexOf("/");
	return (slash >= 0 ? lower.slice(0, slash) : lower).trim();
}

/** Splits a line the way robots-parser does: comment removed, `field: value`. */
function parseLine(raw: string, index: number): ParsedLine {
	const hash = raw.indexOf("#");
	const line = hash >= 0 ? raw.slice(0, hash) : raw;
	const colon = line.indexOf(":");
	if (colon < 0) return { index, raw, field: null, value: "" };
	const field = line.slice(0, colon).trim().toLowerCase();
	return {
		index,
		raw,
		field: field || null,
		value: line.slice(colon + 1).trim(),
	};
}

/** Groups as robots-parser sees them: consecutive `User-agent:` lines start one. */
function parseBlocks(lines: ParsedLine[]): Block[] {
	const blocks: Block[] = [];
	let current: Block | null = null;
	let inAgents = false;
	for (const line of lines) {
		if (!line.field) continue;
		if (line.field === "user-agent") {
			if (!current || !inAgents) {
				current = { agents: [], members: [] };
				blocks.push(current);
			}
			if (line.value) {
				current.agents.push({ line, token: agentToken(line.value) });
			}
			inAgents = true;
			continue;
		}
		inAgents = false;
		current?.members.push(line);
	}
	return blocks;
}

function header(toolVersion: string, source: string, changed: string[]) {
	return [
		`# Generated by AgentCheck ${toolVersion} from ${source}`,
		`# Changed: ${changed.length > 0 ? changed.join("; ") : "nothing, the AI crawlers are already allowed"}`,
	];
}

/**
 * Builds a robots.txt that lets the AI crawlers in `AI_BOTS` reach the audited
 * URL and changes nothing else: every other agent gets the same answers, and
 * each unblocked crawler gets its own group with the `*` group's rules (or, if
 * it had its own group, those rules plus the `*` group's `Disallow` lines)
 * minus the `Disallow` lines that cover the audited URL.
 *
 * `original` null = the site has no robots.txt (404).
 */
export function rewriteRobots(
	original: string | null,
	audited: URL,
	opts: { toolVersion: string; sitemap?: string },
): RobotsRewrite {
	const robotsUrl = new URL("/robots.txt", audited.origin).href;

	if (original === null) {
		const changed = ["created a robots.txt that allows every crawler"];
		const lines = [
			`# Generated by AgentCheck ${opts.toolVersion} for ${robotsUrl} (the site has none)`,
			`# Changed: ${changed.join("; ")}`,
			"",
			"User-agent: *",
			"Allow: /",
		];
		if (opts.sitemap) lines.push("", `Sitemap: ${opts.sitemap}`);
		return { content: `${lines.join("\n")}\n`, changed, blockedBots: [] };
	}

	const body = original.charCodeAt(0) === 0xfeff ? original.slice(1) : original;
	const rawLines = body.split(/\r\n|\r|\n/);
	if (rawLines.length > 0 && rawLines[rawLines.length - 1] === "") {
		rawLines.pop();
	}
	const lines = rawLines.map(parseLine);
	const blocks = parseBlocks(lines);

	const parser = robotsParser(robotsUrl, body);
	const blockedBots: string[] = AI_BOTS.filter(
		(bot) => !(parser.isAllowed(audited.href, bot) ?? true),
	);
	const path = audited.pathname + audited.search;

	if (blockedBots.length === 0) {
		const content = [
			...header(opts.toolVersion, robotsUrl, []),
			"",
			...rawLines,
		];
		return { content: `${content.join("\n")}\n`, changed: [], blockedBots };
	}

	const coversAudited = (pattern: string) =>
		pattern !== "" &&
		robotsParser(robotsUrl, `User-agent: *\nDisallow: ${pattern}`).isAllowed(
			audited.href,
			"*",
		) === false;
	const rulesOf = (matching: Block[], fields: Set<string>) =>
		matching.flatMap((block) =>
			block.members.filter(
				(l) => l.field && fields.has(l.field) && l.value !== "",
			),
		);
	const starBlocks = blocks.filter((b) =>
		b.agents.some((a) => a.token === "*"),
	);

	/** Line index → replacement text, for the lines taken out of shared groups. */
	const replaced = new Map<number, string>();
	const newGroups: string[] = [];
	const changed: string[] = [];

	for (const bot of blockedBots) {
		const token = agentToken(bot);
		const mark = ` # AgentCheck: allow ${bot}`;
		const own = blocks.filter((b) => b.agents.some((a) => a.token === token));
		let rules: ParsedLine[];
		if (own.length > 0) {
			// Its own rules, plus the paths every crawler is kept out of.
			rules = rulesOf(own, RULE_FIELDS);
			const seen = new Set(rules.map((r) => `${r.field}:${r.value}`));
			for (const r of rulesOf(starBlocks, new Set(["disallow"]))) {
				if (!seen.has(`${r.field}:${r.value}`)) rules.push(r);
			}
		} else {
			rules = rulesOf(starBlocks, new Set(["allow", "disallow"]));
		}
		rules = rules.filter(
			(r) => !(r.field === "disallow" && coversAudited(r.value)),
		);
		const out = [`User-agent: ${bot}${mark}`];
		if (!rules.some((r) => r.field === "allow" || r.field === "disallow")) {
			out.push(`Allow: /${mark}`);
		}
		for (const r of rules) {
			out.push(`${FIELD_NAMES[r.field as string]}: ${r.value}${mark}`);
		}
		newGroups.push(...out, "");
		changed.push(`allow ${bot} on ${path}`);

		for (const block of own) {
			for (const agent of block.agents) {
				if (agent.token === token) {
					replaced.set(agent.line.index, `# ${agent.line.raw.trim()}${mark}`);
				}
			}
		}
	}

	// A group left without agents would hand its rules to the group above it.
	for (const block of blocks) {
		if (block.agents.length === 0) continue;
		if (!block.agents.every((a) => replaced.has(a.line.index))) continue;
		const bots = blockedBots.filter((bot) =>
			block.agents.some((a) => a.token === agentToken(bot)),
		);
		for (const line of block.members) {
			if (line.field && RULE_FIELDS.has(line.field)) {
				replaced.set(
					line.index,
					`# ${line.raw.trim()} # AgentCheck: allow ${bots.join(", ")}`,
				);
			}
		}
	}

	const kept = rawLines.map((raw, i) => replaced.get(i) ?? raw);
	// Rules before the first group are ignored; new groups must not adopt them.
	const firstAgent = lines.findIndex((l) => l.field === "user-agent");
	const end = firstAgent < 0 ? lines.length : firstAgent;
	const hasOrphans = lines
		.slice(0, end)
		.some((l) => l.field !== null && RULE_FIELDS.has(l.field));
	const at = hasOrphans ? end : 0;
	const before = kept.slice(0, at);
	if (before.length > 0 && before[before.length - 1]?.trim() !== "") {
		before.push("");
	}
	const content = [
		...header(opts.toolVersion, robotsUrl, changed),
		"",
		...before,
		...newGroups,
		...kept.slice(at),
	];
	return { content: `${content.join("\n")}\n`, changed, blockedBots };
}
